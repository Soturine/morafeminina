/** URL oficial de incorporação (embed) de uma publicação. */
export function instagramEmbedUrl(post: InstagramPost): string {
  const path = post.type === "REEL" ? "reel" : "p";
  return `https://www.instagram.com/${path}/${post.shortcode}/embed/captioned/`;
}

/** Publicações mais recentes primeiro (a planilha já vem em ordem cronológica inversa). */
